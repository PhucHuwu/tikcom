import { mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { getConfig } from '../config.js';

export type Row = Record<string, unknown>;

/** Câu SQL viết theo cú pháp Postgres ($1, $2...), chạy được trên cả Neon và SQLite. */
export interface Driver {
  kind: 'postgres' | 'sqlite';
  query<T = Row>(text: string, params?: unknown[]): Promise<T[]>;
}

const COMMON = (id: string) => `
  CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS sessions (
    id ${id},
    username TEXT NOT NULL,
    started_at BIGINT NOT NULL,
    ended_at BIGINT,
    last_seen BIGINT NOT NULL,
    owner TEXT NOT NULL,
    peak_viewers INTEGER NOT NULL DEFAULT 0,
    total_likes INTEGER NOT NULL DEFAULT 0,
    demo BOOLEAN NOT NULL DEFAULT FALSE
  );
  CREATE TABLE IF NOT EXISTS events (
    id ${id},
    session_id INTEGER NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    eid TEXT NOT NULL,
    ts BIGINT NOT NULL,
    kind TEXT NOT NULL,
    user_id TEXT,
    user_name TEXT,
    text TEXT,
    lang TEXT,
    gift_name TEXT,
    gift_count INTEGER,
    diamonds INTEGER
  );
  CREATE INDEX IF NOT EXISTS idx_events_session ON events(session_id, kind);
  CREATE INDEX IF NOT EXISTS idx_events_eid ON events(session_id, eid);
`;

async function postgres(url: string): Promise<Driver> {
  const { neon } = await import('@neondatabase/serverless');
  const sql = neon(url);
  return {
    kind: 'postgres',
    query: async <T>(text: string, params: unknown[] = []) => (await sql.query(text, params)) as T[],
  };
}

async function sqlite(path: string): Promise<Driver> {
  const { DatabaseSync } = await import('node:sqlite');
  mkdirSync(dirname(path), { recursive: true });
  const db = new DatabaseSync(path);
  db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');
  const toSqlite = (text: string) => text.replace(/\$(\d+)/g, '?$1');
  const toParam = (v: unknown) => (typeof v === 'boolean' ? Number(v) : v === undefined ? null : v);
  return {
    kind: 'sqlite',
    query: async <T>(text: string, params: unknown[] = []) =>
      db.prepare(toSqlite(text)).all(...(params.map(toParam) as never[])) as T[],
  };
}

async function migrate(d: Driver) {
  const schema = COMMON(d.kind === 'postgres' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT');
  if (d.kind === 'sqlite') await upgradeLegacySqlite(d);
  for (const stmt of schema.split(';').map((s) => s.trim()).filter(Boolean)) await d.query(stmt);
}

/** File SQLite từ bản cũ (trước khi tách cho Vercel) thiếu vài cột: thêm vào để giữ lịch sử cũ */
async function upgradeLegacySqlite(d: Driver) {
  const cols = async (table: string) => new Set((await d.query<{ name: string }>(`PRAGMA table_info(${table})`)).map((c) => c.name));
  const sessions = await cols('sessions');
  if (sessions.size && !sessions.has('owner')) {
    await d.query("ALTER TABLE sessions ADD COLUMN owner TEXT NOT NULL DEFAULT ''");
    await d.query('ALTER TABLE sessions ADD COLUMN last_seen BIGINT NOT NULL DEFAULT 0');
    await d.query('UPDATE sessions SET last_seen = COALESCE(ended_at, started_at), ended_at = COALESCE(ended_at, started_at)');
  }
  const events = await cols('events');
  if (events.size && !events.has('eid')) {
    await d.query("ALTER TABLE events ADD COLUMN eid TEXT NOT NULL DEFAULT ''");
  }
  await d.query('DROP TABLE IF EXISTS auth_tokens');
}

let driver: Promise<Driver> | null = null;

/** Có DATABASE_URL thì dùng Postgres (Neon), không thì SQLite trong file cục bộ. */
export function getDriver(): Promise<Driver> {
  if (!driver) {
    const cfg = getConfig();
    // Ổ đĩa trên Vercel bị xóa sau mỗi lần chạy, SQLite sẽ mất dữ liệu
    if (!cfg.databaseUrl && cfg.onVercel) {
      return Promise.reject(new Error('Chưa kết nối cơ sở dữ liệu: thêm Neon trong Vercel → Storage (tự đặt DATABASE_URL) rồi deploy lại'));
    }
    driver = (cfg.databaseUrl ? postgres(cfg.databaseUrl) : sqlite(cfg.dbPath)).then(async (d) => {
      await migrate(d);
      return d;
    });
    driver.catch(() => (driver = null));
  }
  return driver;
}
